-- アップロード済みアイコンの参照を解除する（#763）
--
-- 背景:
-- プロフィールアイコンをユーザーのアップロード方式からプリセット選択方式へ
-- 変更した。アップロード済みの画像ファイルは Fly.io の永続ボリュームごと
-- 破棄するため、users.icon に残ったURLは存在しないファイルを指すことになり、
-- プロフィール画面で壊れた画像が表示されてしまう。
--
-- 対象:
-- users.icon には移行後、プリセットのID（'preset-01' 形式）のみが入る。
-- それ以外の値（アップロードURL）をすべて NULL にする。
--
-- デフォルトのプリセットを割り当てるのではなく NULL にするのは、
-- ユーザーが選んでいないアイコンを勝手に設定しないため。
-- 未設定時はアプリ側でプレースホルダー（人型アイコン）を表示する。
--
-- 冪等性:
-- プリセットIDに一致する行は対象外のため、再実行しても影響はない。

UPDATE users
SET icon = NULL,
    updated_at = CURRENT_TIMESTAMP
WHERE icon IS NOT NULL
  AND icon <> ''
  AND icon NOT IN (
      'preset-01', 'preset-02', 'preset-03', 'preset-04',
      'preset-05', 'preset-06', 'preset-07', 'preset-08'
  );
